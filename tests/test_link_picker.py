def _toasts(app) -> list[str]:
    return [str(t.render()) for t in app.screen.query("Toast")]


def _plains(ol) -> list[str]:
    return [ol.get_option_at_index(i).prompt.plain for i in range(ol.option_count)]


@pytest.mark.parametrize("waiter", ["tw5", "ta2", "to4"])
def test_TC_509_candidates_and_hints_equal_the_oracle(waiter):
    """TC-509 (LLR-502.2): over the kg board with `tw6` waiting on `tw5`, the
    candidates for waiters `tw5`, `ta2` (no start) and `to4` (no dates) — order,
    section, loop and hint — equal the P1 oracle row by row; the forms reached are
    derived from the oracle and guarded == 7 (six timing forms + the loop). RED: a
    done task listed, an unsorted list, a hint off by a day."""
    b = kg_board.build()
    b.task_by_id("tw6").depends_on.append("tw5")
    got = []
    for c in link_candidates(b, b.task_by_id(waiter)):
        if c.loop:
            hint = "⟲ would loop: this → " + " → ".join(t.title for t in c.loop[1:-1]) + " → this"
        else:
            hint = ("✓ linked (↵ removes) · " if c.linked else "") + c.hint
        got.append((c.same_project, c.task.id, hint))
    assert got == TC_509[waiter]
    forms = {re.sub(r"\d+d|[A-Z][a-z]{2} \d+", "#", h.split(" · ")[-1])
             for rows in TC_509.values() for _s, _i, h in rows}
    forms = {f if not f.startswith("⟲") else "⟲" for f in forms}
    assert len(forms) == 7, forms


def test_TC_507_a_link_is_refused_when_it_is_self_closed_or_a_loop():
    """TC-507 (LLR-502.1): the task itself, a closed task and a loop are refused,
    the loop named by its path and shortened in the middle past six names. RED: a
    link written before the check."""
    b = kg_board.build()
    m2 = b.task_by_id("tm2")
    assert link_refusal(b, m2, m2) == "a task cannot wait on itself"
    assert link_refusal(b, m2, b.task_by_id("tw1")) == "Design homepage mockups is closed"
    assert link_refusal(b, m2, b.task_by_id("tm5")) == (
        "would create a loop: Audit dependencies → Beta release to testers → Offline sync "
        "→ Add push notifications → Audit dependencies")
    assert link_refusal(b, m2, b.task_by_id("to4")) is None
    from taskboard.models import Task
    chain = [Task(f"T{i}", phase="Doing", depends_on=[f"T{i - 1}"] if i else [], id=f"T{i}")
             for i in range(9)]
    b.tasks += chain
    long = link_refusal(b, chain[0], chain[8])
    assert long.startswith("would create a loop: T0 → T8 → T7 → … → ") and long.count("→") == 5


def test_TC_508_L_is_one_new_key_painted_at_80_columns():
    """TC-508 (LLR-502.1, ux UX-3): `L` → `link` is the keymap's only new row, in
    the primary layer of group `task`, scoped to the five views with a selection;
    it is painted in the primary key bar at 80 columns in kanban and gantt with no
    key counted as dropped; `BlockerPicker` is gone from the package. RED on base:
    `L` unbound (P-13)."""
    rows = [k for k in KEYMAP if k.keys == "L"]
