async def test_TC_507_the_app_refuses_a_loop_even_when_asked_directly(tmp_path):
    """TC-507 (LLR-502.1; code review T2, battery P14): the picker never offers a
    loop, so the app's own refusal is the last guard — `link_tasks(tm2, tm5)`
    leaves `depends_on` and the undo stack as they were and names the loop. RED:
    the link written before the refusal check."""
